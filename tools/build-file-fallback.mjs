import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const root = process.cwd();
const sources = ['src/materials.js', 'src/simulation.js', 'src/app.js'];

function toClassicScript(source, file) {
  let output = source;
  output = output.replace(/^import\s+[^;]+;\n/gm, '');
  output = output.replace(/\bexport\s+(?=const\s|function\s)/g, '');
  if (file === 'src/materials.js') {
    output = output.replace('const DEFAULTS =', 'var DEFAULTS =');
    output = output.replace('const MATERIAL_SWATCHES =', 'var MATERIAL_SWATCHES =');
  }
  return output.trim();
}

const parts = [];
for (const file of sources) {
  const source = await readFile(join(root, file), 'utf8');
  parts.push(`// ---- ${file} ----\n${toClassicScript(source, file)}`);
}

const banner = `// Generated by tools/build-file-fallback.mjs. Do not edit by hand.\n// This classic-script bundle lets the app run when index.html is opened directly from disk.\n`;
await writeFile(join(root, 'src/app-file-fallback.js'), `${banner}\n${parts.join('\n\n')}\n`, 'utf8');
